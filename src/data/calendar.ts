/**
 * カレンダーの表示方法
 *
 *   'builtin' … このサイトに内蔵のカレンダー（下の休業日データを使用）
 *   'google'  … Googleカレンダーを埋め込む（googleCalendarId の設定が必要）
 *
 * ※ まずは 'builtin' のまま運用し、Googleカレンダーの準備ができたら
 *    'google' に書き換えてください。
 * ※ 'google' 以外の値を書いた場合は、安全のため 'builtin' として動作します。
 */
export const calendarMode: 'builtin' | 'google' = 'builtin'

