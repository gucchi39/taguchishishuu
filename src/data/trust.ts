/* ========================================
   信頼要素（お客様の声・主な取引先／実績・働く人の声）設定ファイル
   ----------------------------------------
   掲載できる内容が揃ったら、このファイルに書き足して
   commit → push すると、サイトに自動で表示されます。
   何も書いていない（空の [ ] のままの）項目は、
   サイト上では「準備中」と表示されます。

   【大切なお願い】
   ・実際にいただいた声・実際の取引だけを載せてください（架空の内容は載せない）。
   ・お客様の社名や個人名を載せるときは、必ず事前にご本人の了承を得てください。
     了承が取れない場合は「筑西市 建設業 A社様」のように匿名にします。
   ・書き方の例は各項目の上の説明文にあります。
     例をコピーして、下の「export const 〜 = []」の行と置き換え
     （行頭の「 * 」は取り除く）、内容を書き換えてください。
   ======================================== */

/**
 * お客様の声（トップページに表示）
 *
 *   name … お客様のお名前（匿名可）
 *   attr … ご依頼内容など（枚数・加工の種類）
 *   body … いただいた声（そのまま、または要約）
 *
 * 書き方の例:
 *   export const testimonials: Testimonial[] = [
 *     {
 *       name: '筑西市 建設業 A社様',
 *       attr: '作業着ロゴ刺繍 50枚',
 *       body: '急ぎのお願いでしたが、仕上がりもきれいで納期にも間に合わせていただきました。',
 *     },
 *     {
 *       name: '桜川市 スポーツ少年団 保護者様',
 *       attr: 'ユニフォーム ネーム刺繍 20枚',
 *       body: '子どもたちの名前を一枚ずつ丁寧に入れていただき、とても喜んでいます。',
 *     },
 *   ]
 */
export type Testimonial = { name: string; attr: string; body: string }
export const testimonials: Testimonial[] = []

/**
 * 主な取引先・実績（トップページ・会社概要ページに表示）
 *
 *   name … 取引先名、または業種・カテゴリ
 *   note … 補足（任意。加工内容など。不要なら省略可）
 *
 * 書き方の例（個社名を出せない場合は、業種・地域でまとめて書きます）:
 *   export const clients: Client[] = [
 *     { name: '筑西市内の建設・製造業', note: 'ユニフォーム刺繍' },
 *     { name: '県内の学校・部活動', note: 'ジャージ ネーム刺繍' },
 *     { name: 'アパレルメーカー様（OEM）' },
 *   ]
 *
 * 書き方の例（社名の掲載について了承をいただいた場合）:
 *     { name: '株式会社〇〇様', note: '制服ロゴ刺繍' },
 */
export type Client = { name: string; note?: string }
export const clients: Client[] = []

/**
 * 働く人の声（採用情報ページに表示）
 *
 *   role  … 仕事内容・担当
 *   years … 勤続年数など
 *   body  … 本人の声（掲載前に本人に内容を確認してもらってください）
 *
 * 書き方の例:
 *   export const staffVoices: StaffVoice[] = [
 *     {
 *       role: '刺繍オペレーター',
 *       years: '入社5年目',
 *       body: '未経験から始めましたが、先輩が一から教えてくれたので安心して続けられています。',
 *     },
 *   ]
 */
export type StaffVoice = { role: string; years: string; body: string }
export const staffVoices: StaffVoice[] = []

/** 項目が空のときに表示する文言 */
export const pendingMessage = '現在準備中です。順次掲載してまいります。'
